"""Rebuild omitted local scoring plans without rewriting a frozen dataset.

Each generated byte sequence must match the already committed manifest hash.
Existing plans are checked and never overwritten. No model calls are made.
"""

from __future__ import annotations

import hashlib
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "backend" / "src"))

from demopilot.quotation_contract import compile_acceptance


def main() -> None:
    dataset = ROOT / "evaluation_sets" / "quotation-reliability-v2"
    manifest = json.loads((dataset / "manifest.json").read_text("utf-8"))
    prefix = "evaluation_sets/quotation-reliability-v2/private/"
    created = 0
    verified = 0
    for relative, expected_hash in manifest["files"].items():
        if not relative.startswith(prefix):
            continue
        name = Path(relative).stem
        app_id, version = name.rsplit("-v", 1)
        contract = json.loads(
            (ROOT / "testdata" / app_id / f"contract-v{version}.json").read_text("utf-8")
        )
        value = compile_acceptance(contract, private=True)
        serialized = json.dumps(value, ensure_ascii=False, indent=2).encode("utf-8")
        # The original Windows writer used native CRLF. Select only bytes that
        # match its frozen hash, even when rebuilding on a different platform.
        candidates = (serialized, serialized.replace(b"\n", b"\r\n"))
        data = next(
            (candidate for candidate in candidates
             if hashlib.sha256(candidate).hexdigest() == expected_hash),
            None,
        )
        if data is None:
            raise RuntimeError(f"Generated plan differs from frozen manifest: {relative}")
        target = ROOT / relative
        if target.exists():
            if hashlib.sha256(target.read_bytes()).hexdigest() != expected_hash:
                raise RuntimeError(f"Existing plan differs; refusing overwrite: {relative}")
        else:
            target.parent.mkdir(parents=True, exist_ok=True)
            with target.open("xb") as stream:
                stream.write(data)
            created += 1
        verified += 1
    if verified == 0:
        raise RuntimeError("Frozen manifest declares no scoring plans")
    print(json.dumps({"created": created, "verified": verified, "public_files_changed": 0}))


if __name__ == "__main__":
    main()
